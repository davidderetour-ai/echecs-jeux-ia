export function searchUrl(engineId,query){
 const engine=SEARCH_ENGINES.find(x=>x.id===engineId);
 const q=String(query||"").trim();
 if(!engine)throw Error("Moteur inconnu");
 if(!q||q.length>350)throw Error("Requête invalide (maximum 350 caractères).");
 return engine.base+encodeURIComponent(q);
}
