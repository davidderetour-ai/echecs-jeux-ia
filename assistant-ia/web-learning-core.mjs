export function keywordTokens(q){return [...new Set(String(q||"").normalize("NFD").replace(/[\u0300-\u036f]/g,"").toLowerCase().match(/[a-z0-9]{3,}/g)||[])].filter(x=>!["quel","quelle","quels","pour","dans","avec","comment","sont","that","this","from"].includes(x));}
export function relevantExcerpts(question,pages){
 const terms=keywordTokens(question);
 return (Array.isArray(pages)?pages:[]).slice(0,3).map((p)=>{
  const body=String(p?.text||"").replace(/\s+/g," ").slice(0,8500);
  const sentences=body.match(/[^.!?]+[.!?]?/g)||[];
  const excerpts=sentences.map(s=>({text:s.trim(),score:terms.filter(t=>s.normalize("NFD").replace(/[\u0300-\u036f]/g,"").toLowerCase().includes(t)).length})).filter(x=>x.text.length>=16).sort((a,b)=>b.score-a.score).slice(0,3).map(x=>x.text.slice(0,480));
  return {url:String(p.url||""),title:String(p.title||""),excerpts,matched:excerpts.some(e=>terms.some(t=>e.toLowerCase().includes(t)))};
 });
}
export function findWebCourse(q){
 const terms=keywordTokens(q);
 if(!terms.length)return null;
 const scored=WEB_COURSES.map(course=>({course,score:terms.reduce((n,t)=>n+(course.title.toLowerCase().includes(t)?4:0)+(course.lesson.toLowerCase().includes(t)?1:0),0)})).sort((a,b)=>b.score-a.score);
 return scored[0]?.score>=4?scored[0].course:null;
}
